    public static function sanitizeForPhpWord(string $html): string 
    {
        $html = trim($html);
        // quita BOM si lo hubiera
        $html = preg_replace('/^\xEF\xBB\xBF/', '', $html);

        // elimina párrafos/div vacíos iniciales (causan página en blanco)
        $html = preg_replace('/^(?:\s|&nbsp;|<br\s*\/?>|<p>(?:\s|&nbsp;|<br\s*\/?>)*<\/p>)+/i', '', $html);

        // quita clases/propiedades de Word (Mso*)
        $html = preg_replace('/\sclass="[^"]*Mso[^"]*"/i', '', $html);
        $html = preg_replace('/mso-[a-z\-]+\s*:\s*[^;"\']+;?/i', '', $html);

        // elimina page-break CSS
        $html = preg_replace('/page-break-(before|after)\s*:\s*always;?/i', '', $html);

        // normaliza anchos con unidades: cm/pt → pt enteros (PHPWord odia decimales)
        $html = preg_replace_callback('/width\s*:\s*([0-9]+(?:\.[0-9]+)?)\s*cm/i', function($m){
            $pt = (int) round((float)$m[1] * 28.3464567); // 1cm = 28.346pt
            return "width:{$pt}pt";
        }, $html);
        $html = preg_replace_callback('/width\s*:\s*([0-9]+(?:\.[0-9]+)?)\s*pt/i', function($m){
            return "width:" . (int) round((float)$m[1]) . "pt";
        }, $html);

        // quita &nbsp; sueltos entre tablas/lineas
        $html = preg_replace('/<(div|p)>\s*&nbsp;\s*<\/\1>/i', '', $html);

        // colapsa espacios repetidos
        $html = preg_replace('/(&nbsp;|\s){2,}/', ' ', $html);

        return $html;
    }

    /**
     * Une marcadores {[...]} partidos en runs y elimina tags solo DENTRO del marcador.
     * Luego puedes usar str_replace('{[CLAVE]}', valor) sin romper el XML.
    */
    public static function normalizeMarkers(string $xml): string {
        // 1) Asegura que el inicio y fin del marcador no tengan tags intermedios
        $xml = preg_replace('/\{\s*(?:<[^>]+>\s*)*\[/', '{[', $xml);
        $xml = preg_replace('/\]\s*(?:<[^>]+>\s*)*\}/', ']}', $xml);

        // 2) En cada marcador, quita CUALQUIER etiqueta <...> interna
        //    y espacios para que quede exactamente {[CLAVE]}
        $xml = preg_replace_callback('/\{\[(.*?)\]\}/s', function ($m) {
            $inside = preg_replace('/<[^>]+>/', '', $m[1]); // quita tags
            $inside = preg_replace('/\s+/', '', $inside);   // quita espacios
            return '{[' . $inside . ']}';
        }, $xml);

        return $xml;
    }


    /**
     * Reemplaza placeholders tipo {[NOMBRE]} dentro de un DOCX sin corromperlo.
     * - Tolera placeholders “rotos” entre varios <w:t>
     * - Escapa XML y fuerza UTF-8 válido
     * - Evita backreferences ($1) usando preg_replace_callback
    */
    public static function replacePlaceholdersInDocx(string $docxPath, array $replacements, string $outPath, string $tmpPath)
    {
        try {
            $tmpDir = $tmpPath . DIRECTORY_SEPARATOR . 'docx_replace_' . uniqid();
            simad_util::createPath($tmpDir);
            //******************************************************************************************
            if (!copy($docxPath, $outPath)) throw new RuntimeException("No pude copiar a $outPath");
            //******************************************************************************************
            $zip = new ZipArchive();
            if ($zip->open($outPath) !== true) {
                throw new RuntimeException("No se pudo abrir DOCX origen");
            }
            //******************************************************************************************
            $xml = $zip->getFromName('word/document.xml');
            if ($xml === false) {
                $zip->close();
                throw new RuntimeException("word/document.xml no se encontro el archivo");
            }
            if ($xml === '') {
                $zip->close();
                throw new RuntimeException("word/document.xml esta ilegible o sin información");
            }            
            //******************************************************************************************
            libxml_use_internal_errors(true);
            //******************************************************************************************
            $xml = simad_util::normalizeMarkers($xml);
            foreach ($replacements as $k => $v) {
                $safe = htmlspecialchars((string)$v, ENT_QUOTES | ENT_XML1, 'UTF-8');
                $xml = str_replace('{['.$k.']}', $safe, $xml);
            }
            //******************************************************************************************
            // Validar que el XML siga bien formado antes de escribir
            $ok = simplexml_load_string($xml);
            if ($ok === false) {
                $errs = array_map(function($e){ return trim($e->message); }, libxml_get_errors());
                libxml_clear_errors();
                error_log(implode(' | ', $errs));
                throw new RuntimeException("document.xml error de sintaxis: ".implode(' | ', $errs));
            }
            //******************************************************************************************
            $zip->deleteName('word/document.xml');
            $zip->addFromString('word/document.xml', $xml);
            $zip->close();
            //******************************************************************************************
            return true;
        } catch (\Exception $th) {
            error_log($th->getMessage());
            return false;
        } catch (\Throwable $th) {
            error_log($th->getMessage());
            return false;
        }
    }

    /**
     * Lee custom properties de un DOCX (para validar HMAC/UUID)
     * @param string ruta absoluta al documento de word
     * @return mixed array con las propiedades del documento 
    */
    public static function readCustomPropsFromDocx(string $docxPath): array
    {
        try {
            $out = [];
            $zip = new ZipArchive();
            if ($zip->open($docxPath) !== true) {
                throw new RuntimeException('No se pudo abrir el DOCX.');
            }

            $xml = $zip->getFromName('docProps/custom.xml');
            $zip->close();

            if ($xml === false) {
                // No hay propiedades personalizadas
                return $out;
            }

            // Quita BOM si existe
            $xml = preg_replace('/^\xEF\xBB\xBF/', '', $xml);

            $dom = new DOMDocument();
            // Evita cargar entidades externas
            $ok = @$dom->loadXML($xml, LIBXML_NONET | LIBXML_NOBLANKS);
            if (!$ok) {
                throw new RuntimeException('custom.xml inválido');
            }

            $xp = new DOMXPath($dom);
            // Namespaces estándar de OOXML
            $xp->registerNamespace('cp', 'http://schemas.openxmlformats.org/officeDocument/2006/custom-properties');
            $xp->registerNamespace('vt', 'http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes');

            // Selecciona cada propiedad
            foreach ($xp->query('/cp:Properties/cp:property') as $prop) {
                /** @var DOMElement $prop */
                $name = $prop->getAttribute('name');
                if ($name === '') { continue; }

                // El valor real está en el PRIMER hijo elemento, normalmente vt:lpwstr,
                // pero a veces viene envuelto en vt:variant/vt:lpwstr
                $valueNode = null;

                // 1) directo: /cp:property/vt:* 
                foreach ($prop->childNodes as $ch) {
                    if ($ch instanceof DOMElement && $ch->namespaceURI === 'http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes') {
                        $valueNode = $ch;
                        break;
                    }
                }
                // 2) envuelto: /cp:property/vt:variant/vt:*
                if ($valueNode === null) {
                    $n = $xp->query('./vt:variant/*', $prop);
                    if ($n && $n->length) {
                        $valueNode = $n->item(0);
                    }
                }

                if (!$valueNode instanceof DOMElement) {
                    // sin valor legible
                    continue;
                }

                $local = $valueNode->localName;   // lpwstr, i4, r8, bool, filetime, date, ...
                $raw   = $valueNode->textContent;

                // Normaliza tipos
                switch ($local) {
                    case 'bool':
                        $val = in_array(strtolower(trim($raw)), ['true','1','-1','yes'], true);
                        break;
                    case 'i1': case 'i2': case 'i4': case 'i8':
                    case 'ui1': case 'ui2': case 'ui4': case 'ui8':
                        $val = (int)trim($raw);
                        break;
                    case 'r4': case 'r8': // float/double
                        $val = (float)str_replace(',', '.', trim($raw));
                        break;
                    case 'filetime':      // formato ISO/FILETIME; devuélvelo como string o DateTime
                    case 'date':
                        $val = trim($raw);
                        // Si quieres DateTime:
                        // $val = (new DateTime($val));
                        break;
                    default: // lpwstr, bstr, string y otros → texto
                        $val = trim($raw);
                }

                $out[$name] = $val;
            }

            return $out;
        } catch (\Exception $th) {
            return array();
        } catch (\Throwable $th) {
            return array();
        }
    }

