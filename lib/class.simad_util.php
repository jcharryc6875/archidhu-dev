                <a:stretch><a:fillRect/></a:stretch>
                </pic:blipFill>
                <pic:spPr>
                <a:xfrm>
                    <a:off x="0" y="0"/>
                    <a:ext cx="'.$cx.'" cy="'.$cy.'"/>
                </a:xfrm>
                <a:prstGeom prst="rect"><a:avLst/></a:prstGeom>
                </pic:spPr>
            </pic:pic>
            </a:graphicData>
        </a:graphic>
        </wp:inline>
    </w:drawing>
    </w:r>';
        };

        $normalizeMarkers = function(string $xml): string {
            $xml = preg_replace('/\{\s*(?:<[^>]+>\s*)*\[/', '{[', $xml);
            $xml = preg_replace('/\]\s*(?:<[^>]+>\s*)*\}/', ']}', $xml);
            return preg_replace_callback('/\{\[(.*?)\]\}/s', function($m){
                $inside = preg_replace('/<[^>]+>/', '', $m[1]);
                $inside = preg_replace('/\s+/', '', $inside);
                return '{['.$inside.']}';
            }, $xml);
        };

        $addRelationship = function(string $relsXml, string $rId, string $target): string {
            return preg_replace(
                '#</Relationships>#',
                '<Relationship Id="'.$rId.'" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="'.$target.'"/></Relationships>',
                $relsXml, 1
            );
        };

        $nextRidOf = function(string $relsXml): int {
            if (preg_match_all('/Id="rId(\d+)"/', $relsXml, $m) && $m[1]) {
                return max(array_map('intval', $m[1])) + 1;
            }
            return 1;
        };

        // NUEVO: asegura namespaces de dibujo en la raíz del XML
        $ensureDrawingNamespaces = function(string $xml): string {
            // solo tocamos la PRIMER etiqueta raíz (document, hdr, ftr)
            return preg_replace_callback(
                '#<(w:(?:document|hdr|ftr))([^>]*)>#',
                function($m) {
                    $tag  = $m[1];
                    $attr = $m[2];
                    $ns   = [
                        'wp'  => 'http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing',
