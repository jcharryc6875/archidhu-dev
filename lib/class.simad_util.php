            }
        }

        $xmlByPart = [];
        $relsByPartPath = [];
        $relsXmlByPart = [];

        foreach ($parts as $partPath) {
            $xml = $zip->getFromName($partPath);
            if ($xml === false) continue;

            // normaliza marcadores y asegura namespaces de dibujo
            $xml = $normalizeMarkers($xml);
            $xml = $ensureDrawingNamespaces($xml);

            $xmlByPart[$partPath] = $xml;

            $relsPath = preg_replace('#^word/([^/]+)\.xml$#', 'word/_rels/$1.xml.rels', $partPath);
