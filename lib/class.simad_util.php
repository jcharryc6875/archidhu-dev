        }

        if (!copy($docxIn, $docxOut)) {
            throw new RuntimeException("No pude copiar DOCX a destino");
        }

        $zip = new ZipArchive();
        if ($zip->open($docxOut) !== true) {
            throw new RuntimeException("No pude abrir DOCX destino");
        }

        $parts = ['word/document.xml'];
        for ($i=1; $i<=10; $i++) {
