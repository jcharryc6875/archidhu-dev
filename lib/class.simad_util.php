     * - Crea relaciones rId por parte (document/header/footer) y embeber media/...
     * - Soporta tamaño en cm o px (wcm/hcm/wpx/hpx)
     *
     * $images = [
     *   'FIRMA_MECANICA' => ['path' => '/imgs/firma.png', 'wcm' => 5.0, 'hcm' => 2.0],
     *   'LOGO'           => ['path' => '/imgs/logo.png',  'wpx' => 220, 'hpx' => 80 ],
     * ];
     */
    public static function replaceImagesBatchInDocx(string $docxIn, array $images, string $docxOut): void {
        $EMU_PER_CM = 360000;  // 1cm = 360000 EMUs
        $EMU_PER_PX = 9525;    // 1px a 96dpi

        $toEmu = function(array $cfg) use ($EMU_PER_CM, $EMU_PER_PX): array {
            if (isset($cfg['wcm'], $cfg['hcm'])) {
                return [(int)round($cfg['wcm']*$EMU_PER_CM), (int)round($cfg['hcm']*$EMU_PER_CM)];
            } elseif (isset($cfg['wpx'], $cfg['hpx'])) {
                return [(int)round($cfg['wpx']*$EMU_PER_PX), (int)round($cfg['hpx']*$EMU_PER_PX)];
            }
            // tamaño por defecto
            return [(int)round(5*$EMU_PER_CM), (int)round(2*$EMU_PER_CM)];
        };

