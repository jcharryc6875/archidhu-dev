    /**
     * Valida archivo recibido por SOAP: solo PDF o Word (DOC/DOCX).
     * Entrada: $filename (string) y $b64 (string)
     * Retorna: info del tipo permitido o error.
     *
     * @return array{ok:bool,type:?string,ext:?string,error:?string,clean_name:?string}
     */
    public static function validateBase64FilePdfOrWord(string $filename, string $b64, int $maxBytes = 105000000): array
    {
        // 1) Sanitizar nombre (evita rutas/..\ y caracteres raros)
        $cleanName = trim($filename);
        $cleanName = str_replace(["\0", "\\", "/"], "_", $cleanName);
        $cleanName = preg_replace('/\s+/', ' ', $cleanName);
        $cleanName = preg_replace('/[^\w\.\-\(\)\s]/u', '_', $cleanName);

        // Extensión reportada (solo para coherencia, NO para decidir)
        $nameExt = strtolower(pathinfo($cleanName, PATHINFO_EXTENSION));

        // 2) Normalizar base64
        $b64 = trim($b64);
        $b64 = preg_replace('/\s+/', '', $b64);

        // 3) Chequeo rápido de longitud/tamaño aproximado antes de decodificar completo
        // Aproximación bytes = len(base64)*3/4 - padding
        $len = strlen($b64);
        if ($len < 16) {
            return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>'Base64 muy corto','clean_name'=>$cleanName];
        }
        $padding = 0;
        if (substr($b64, -2) === '==') $padding = 2;
        elseif (substr($b64, -1) === '=') $padding = 1;
        $approxBytes = (int)(($len * 3 / 4) - $padding);

        if ($approxBytes <= 0) {
            return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>'Base64 inválido (tamaño)','clean_name'=>$cleanName];
        }
        if ($approxBytes > $maxBytes) {
            return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>"Archivo excede el máximo permitido ({$maxBytes} bytes)",'clean_name'=>$cleanName];
        }

        // 4) Decodificar solo un chunk (para validar firma sin gastar RAM)
        $chunkBytes = 8192;
        $chunkB64Len = (int)(ceil($chunkBytes / 3) * 4);
        $b64Chunk = substr($b64, 0, $chunkB64Len);

        $bin = base64_decode($b64Chunk, true);
        if ($bin === false || $bin === '') {
            return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>'Base64 inválido (decode strict)','clean_name'=>$cleanName];
        }

        // 5) Detectar por firma
        // PDF: %PDF-
        if (strncmp($bin, "%PDF-", 5) === 0) {
            // coherencia opcional
            if ($nameExt && $nameExt !== 'pdf') {
                // puedes decidir si solo advertir o rechazar
                // aquí lo rechazo para evitar confusión
                return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>"Extensión no coincide (nombre .$nameExt, contenido PDF)",'clean_name'=>$cleanName];
            }
            return ['ok'=>true,'type'=>'pdf','ext'=>'pdf','error'=>null,'clean_name'=>$cleanName];
        }

        // DOC (Word 97-2003): OLE
        $oleSig = "\xD0\xCF\x11\xE0\xA1\xB1\x1A\xE1";
        if (strncmp($bin, $oleSig, 8) === 0) {
            // Confirmación ligera de Word dentro del chunk
            if (strpos($bin, "WordDocument") !== false) {
                if ($nameExt && $nameExt !== 'doc') {
                    return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>"Extensión no coincide (nombre .$nameExt, contenido DOC)",'clean_name'=>$cleanName];
                }
                return ['ok'=>true,'type'=>'doc','ext'=>'doc','error'=>null,'clean_name'=>$cleanName];
            }
            return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>'Archivo OLE recibido pero no parece Word (.doc)','clean_name'=>$cleanName];
        }

        // DOCX: ZIP + OOXML markers
        $isZip = (
            strncmp($bin, "PK\x03\x04", 4) === 0 ||
            strncmp($bin, "PK\x05\x06", 4) === 0 ||
            strncmp($bin, "PK\x07\x08", 4) === 0
        );
        if ($isZip) {
            // Indicadores típicos en OOXML (puede que no aparezcan en 8KB, pero normalmente sí)
            $looksDocx = (strpos($bin, "[Content_Types].xml") !== false) && (strpos($bin, "word/") !== false);

            if ($looksDocx) {
                if ($nameExt && $nameExt !== 'docx') {
                    return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>"Extensión no coincide (nombre .$nameExt, contenido DOCX)",'clean_name'=>$cleanName];
                }
                return ['ok'=>true,'type'=>'docx','ext'=>'docx','error'=>null,'clean_name'=>$cleanName];
            }

            // Si quieres ser menos estricto con DOCX (por si el chunk no alcanzó):
            // puedes aceptar ZIP y luego validar definitivamente guardando y abriendo con ZipArchive.
            return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>'ZIP recibido pero no se pudo confirmar que sea DOCX','clean_name'=>$cleanName];
        }

        return ['ok'=>false,'type'=>null,'ext'=>null,'error'=>'Tipo no permitido: solo PDF o Word (DOC/DOCX)','clean_name'=>$cleanName];
    }

