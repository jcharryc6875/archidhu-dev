    /**
     * validarPDF function
     * verifica que un archivo no este dañado o ilegible
     * @return bool true|false si el archivo es legible retorna true de lo contrario false
     */
    public static function validarPDF($archivo) {
        try {
            if (!file_exists($archivo)) {
                return false;
            }

            // Leer primeros bytes para verificar firma PDF
            $handle = fopen($archivo, 'rb');
            if (!$handle) return false;

            $header = fread($handle, 5);
            fclose($handle);

            // Verificar firma de archivo PDF (%PDF-)
            return strpos($header, '%PDF-') === 0;
        } catch (\Exception $th) {
            return false;
        } catch (\Throwable $th) {
            return false;
        }
    }

    /**
     * verificarIntegridadArchivo function
     * verifica que un archivo no este dañado o ilegible
     * @return bool true|false si el archivo es legible retorna true de lo contrario false
     */
    public static function verificarIntegridadArchivo($archivo, $tamanoEsperado = null) {
        if (!file_exists($archivo)) {
            return false;
        }

        $tamanoReal = filesize($archivo);

        // Verificar tamaño
        if ($tamanoEsperado !== null && $tamanoReal != $tamanoEsperado) {
            error_log("Tamaño incorrecto: esperado {$tamanoEsperado}, obtenido {$tamanoReal}");
            return false;
        }

        // Verificar si el archivo está vacío
        if ($tamanoReal === 0) {
            error_log("Archivo vacío: " . $archivo);
            return false;
        }

        // Intentar leer el archivo para verificar que no esté corrupto
        try {
            $handle = @fopen($archivo, 'r');
            if ($handle) {
                $primerosBytes = fread($handle, 1024);
                fclose($handle);
                
                // Verificar si son todos bytes nulos (archivo corrupto)
                if (trim($primerosBytes) === '' && $tamanoReal > 100) {
                    error_log("Archivo parece corrupto (bytes nulos): " . $archivo);
                    return false;
                }
            }
        } catch (Exception $e) {
            error_log("Error verificando archivo: " . $e->getMessage());
            return false;
        }

        return true;
    }
    
    public static function NormalizePath($path)
    {
        $parts = array();// Array to build a new path from the good parts
        $path = str_replace('\\', '/', $path);// Replace backslashes with forwardslashes
        $path = preg_replace('/\/+/', '/', $path);// Combine multiple slashes into a single slash
        $segments = explode('/', $path);// Collect path segments
        $test = '';// Initialize testing variable
        foreach($segments as $segment)
        {
            if($segment != '.')
            {
                $test = array_pop($parts);
                if(is_null($test))
                    $parts[] = $segment;
                else if($segment == '..')
                {
                    if($test == '..')
                        $parts[] = $test;
    
                    if($test == '..' || $test == '')
                        $parts[] = $segment;
                }
                else
                {
                    $parts[] = $test;
                    $parts[] = $segment;
                }
            }
        }
        return implode(DIRECTORY_SEPARATOR, $parts);
    }
    
