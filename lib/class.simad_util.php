            }
            $relsByPartPath[$partPath] = $relsPath;
            $relsXmlByPart[$partPath]  = $relsXml;
        }

        foreach ($images as $key => $cfg) {
            if (!isset($cfg['path']) || !is_file($cfg['path'])) {
                continue;
            }
            $bytes = file_get_contents($cfg['path']);
            $ext   = strtolower(pathinfo($cfg['path'], PATHINFO_EXTENSION)) ?: 'png';
            list($cx, $cy) = $toEmu($cfg);

            foreach (array_keys($xmlByPart) as $partPath) {
                $tag = '{['.$key.']}';
                if (strpos($xmlByPart[$partPath], $tag) === false) continue;

                $mediaName = 'media/'.uniqid('img_'.$key.'_').'.'.$ext;
                $zip->addFromString('word/'.$mediaName, $bytes);

                $next = $nextRidOf($relsXmlByPart[$partPath]);
                $rId  = 'rId'.$next;
                $relsXmlByPart[$partPath] = $addRelationship($relsXmlByPart[$partPath], $rId, $mediaName);

                $drawing = $makeDrawing($rId, $cx, $cy, $next);
                $xmlByPart[$partPath] = str_replace($tag, $drawing, $xmlByPart[$partPath], $num);
            }
        }

        libxml_use_internal_errors(true);
        foreach ($xmlByPart as $partPath => $xml) {
            if (simplexml_load_string($xml) === false) {
                $errs = array_map(function($e){ return trim($e->message); }, libxml_get_errors());
                libxml_clear_errors();
                throw new RuntimeException("XML inválido en $partPath: ".implode(' | ', $errs));
            }
            $zip->deleteName($partPath);
            $zip->addFromString($partPath, $xml);

            $relsPath = $relsByPartPath[$partPath];
            $zip->deleteName($relsPath);
            $zip->addFromString($relsPath, $relsXmlByPart[$partPath]);
        }

