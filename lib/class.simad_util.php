    public static  function descomponerCadena($cadena) 
    {
        $cadena = trim($cadena);
        if ($cadena === '') {
            return ['joins' => [], 'columna' => null];
        }

        $partes = array_map('trim', explode('.', $cadena));
        $columna = array_pop($partes); // último elemento
        $joins = [];

        foreach ($partes as $parte) {
            if ($parte === '') {
                continue;
            }

            if (preg_match('/^([A-Z_]+)(?:\[([A-Z_]+)\])?$/', $parte, $m)) {
                $joins[] = [
                    'tabla' => $m[1],
                    'campo_relacion' => $m[2] ?? null,
                    'raw' => $parte,
                ];
            }
        }

        return ['joins' => $joins, 'columna' => trim($columna)];
    }

    public static function generarSqlCamposMetadatos(array $campos_metadatos_bd, $joinType = 'LEFT JOIN', $defaultBaseTable = 'COM_RECIBIDA')
    {
        $selectFields = [];
        $joinClauses = [];
        $baseTable = null;

        foreach ($campos_metadatos_bd as $field) {
            $field = trim($field);
            if ($field === '') {
                continue;
            }

            $parsed = self::descomponerCadena($field);
            if ($parsed['columna'] === null) {
                continue;
            }

            if (!empty($parsed['joins'])) {
                if ($baseTable === null) {
                    $baseTable = $parsed['joins'][0]['tabla'];
                }

                $joinCount = count($parsed['joins']);
                for ($i = 0; $i < $joinCount - 1; $i++) {
                    $current = $parsed['joins'][$i];
                    $next = $parsed['joins'][$i + 1];

                    $joinField = $current['campo_relacion'];
                    if (!$joinField) {
                        $joinField = self::inferCampoRelacion($current, $next, $parsed['columna']);
                    }

                    if (empty($joinField)) {
                        continue;
                    }

                    $joinKey = sprintf(
                        '%s.%s=%s.%s',
                        $current['tabla'],
                        $joinField,
                        $next['tabla'],
                        $joinField
                    );

                    if (!isset($joinClauses[$joinKey])) {
                        $joinClauses[$joinKey] = sprintf(
                            '%s %s ON %s.%s = %s.%s',
                            $joinType,
                            $next['tabla'],
                            $current['tabla'],
                            $joinField,
                            $next['tabla'],
                            $joinField
                        );
                    }
                }

                $lastJoin = $parsed['joins'][$joinCount - 1];
                $selectFields[] = sprintf('%s.%s', $lastJoin['tabla'], $parsed['columna']);
            } else {
                if ($baseTable === null) {
                    $baseTable = $defaultBaseTable;
                }
                $selectFields[] = sprintf('%s.%s', $baseTable, $parsed['columna']);
            }
        }

        if ($baseTable === null) {
            $baseTable = $defaultBaseTable;
        }

        $selectFields = array_values(array_unique($selectFields));

        if (empty($selectFields)) {
            return [
                'sql' => null,
                'select' => [],
                'joins' => [],
                'base_table' => $baseTable
            ];
        }

        $sql = sprintf(
            "SELECT %s\nFROM %s",
            implode(",\n       ", $selectFields),
            $baseTable
        );

        if (!empty($joinClauses)) {
            $sql .= "\n" . implode("\n", $joinClauses);
        }

        return [
            'sql' => $sql,
            'select' => $selectFields,
            'joins' => array_values($joinClauses),
            'base_table' => $baseTable
        ];
    }

    protected static function inferCampoRelacion(array $current, array $next, $columna = null)
    {
        $candidates = [];

        if ($columna && preg_match('/ID$/', $columna)) {
            $candidates[] = $columna;
        }

        $nextTableNormalized = preg_replace('/[^A-Z0-9]/', '', $next['tabla']);
        if ($nextTableNormalized) {
            $candidates[] = $nextTableNormalized . '_ID';
        }

        $nextTableUpper = strtoupper($next['tabla']);
        if ($nextTableUpper !== $nextTableNormalized) {
            $candidates[] = $nextTableUpper . '_ID';
        }

        foreach ($candidates as $candidate) {
            if (!$candidate) {
                continue;
            }

            $candidate = trim($candidate);
            if ($candidate === '') {
                continue;
            }

            if (!preg_match('/ID$/', $candidate)) {
                continue;
            }

            return $candidate;
        }

        return null;
    }

